import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';

export interface EmbeddedAssetManifestEntry {
  readonly path: string;
  readonly content: string;
  readonly mimeType: string;
  readonly hash: string;
}

const mimeTypes: Readonly<Record<string, string>> = {
  '.css': 'text/css; charset=utf-8',
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
  '.ico': 'image/x-icon',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
};

export interface EmbedWebAssetsOptions {
  readonly repositoryRoot?: string;
  readonly inputPath?: string;
  readonly outputPath?: string;
}

async function filesUnder(directory: string): Promise<string[]> {
  const entries = (await readdir(directory, { withFileTypes: true })).sort((left, right) =>
    left.name.localeCompare(right.name),
  );
  const files: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await filesUnder(path)));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

async function resolveAssetRoot(inputPath: string): Promise<string> {
  if (
    await stat(join(inputPath, 'index.html'))
      .then(() => true)
      .catch(() => false)
  )
    return inputPath;
  const browserPath = join(inputPath, 'browser');
  if (
    await stat(join(browserPath, 'index.html'))
      .then(() => true)
      .catch(() => false)
  ) {
    return browserPath;
  }
  return inputPath;
}

function sourcePath(entryPath: string, root: string): string {
  return `/${relative(root, entryPath).split(sep).join('/')}`;
}

export async function readEmbeddedAssetManifest(
  options: Omit<EmbedWebAssetsOptions, 'outputPath'> = {},
): Promise<EmbeddedAssetManifestEntry[]> {
  const root = resolve(options.repositoryRoot ?? process.cwd());
  const inputPath = await resolveAssetRoot(resolve(root, options.inputPath ?? 'dist/web'));
  const files = await filesUnder(inputPath);
  return Promise.all(
    files.map(async (file) => {
      const bytes = await readFile(file);
      return {
        path: sourcePath(file, inputPath),
        content: bytes.toString('base64'),
        mimeType: mimeTypes[extname(file).toLowerCase()] ?? 'application/octet-stream',
        hash: createHash('sha256').update(bytes).digest('hex'),
      };
    }),
  );
}

export function renderEmbeddedAssetsModule(entries: readonly EmbeddedAssetManifestEntry[]): string {
  const manifest = JSON.stringify(entries, null, 2);
  return `// Generated by scripts/build/embed-web-assets.ts. Do not edit.\nimport { Buffer } from 'node:buffer';\nimport type { EmbeddedAssetMetadata, EmbeddedAssets } from './embedded-assets';\n\nexport const embeddedAssetManifest = ${manifest} as const;\nexport const embeddedAssets: EmbeddedAssets = Object.fromEntries(\n  embeddedAssetManifest.map((entry) => [entry.path, Uint8Array.from(Buffer.from(entry.content, 'base64'))]),\n);\nexport const embeddedAssetMetadata: Readonly<Record<string, EmbeddedAssetMetadata>> = Object.fromEntries(\n  embeddedAssetManifest.map((entry) => [entry.path, { hash: entry.hash, mimeType: entry.mimeType }]),\n);\n`;
}

export async function embedWebAssets(options: EmbedWebAssetsOptions = {}): Promise<{
  readonly inputPath: string;
  readonly outputPath: string;
  readonly entries: readonly EmbeddedAssetManifestEntry[];
}> {
  const root = resolve(options.repositoryRoot ?? process.cwd());
  const inputPath = await resolveAssetRoot(resolve(root, options.inputPath ?? 'dist/web'));
  const outputPath = resolve(
    root,
    options.outputPath ?? 'dist/release/embedded-assets.generated.ts',
  );
  const entries = await readEmbeddedAssetManifest({ repositoryRoot: root, inputPath });
  if (!entries.some((entry) => entry.path === '/index.html')) {
    throw new Error(`Web asset build is missing ${join(inputPath, 'index.html')}`);
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderEmbeddedAssetsModule(entries), 'utf8');
  return { inputPath, outputPath, entries };
}

if (import.meta.main) {
  const result = await embedWebAssets();
  console.log(
    `Embedded ${result.entries.length} web assets into ${relative(process.cwd(), result.outputPath)}`,
  );
}

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import packageManifest from '../../package.json' with { type: 'json' };
import { embedWebAssets } from './embed-web-assets';

export const RELEASE_TARGETS = [
  'linux-x64',
  'linux-arm64',
  'macos-x64',
  'macos-arm64',
  'windows-x64',
] as const;

export type ReleaseTarget = (typeof RELEASE_TARGETS)[number];

export interface CompileBinaryOptions {
  readonly repositoryRoot?: string;
  readonly targets?: readonly ReleaseTarget[];
  readonly version?: string;
  readonly commitHash?: string;
  readonly commandRunner?: (command: string[]) => Promise<number>;
}

export function releaseVersion(
  environment: Record<string, string | undefined> = process.env,
): string {
  const tag = environment['MYADMIN_VERSION'] || environment['GITHUB_REF_NAME'];
  return tag?.replace(/^v/, '') || packageManifest.version;
}

export function releaseCommitHash(
  environment: Record<string, string | undefined> = process.env,
): string {
  const configured = environment['MYADMIN_COMMIT_HASH'] || environment['GITHUB_SHA'];
  if (configured) return configured;
  const result = Bun.spawnSync(['git', 'rev-parse', 'HEAD'], { stdout: 'pipe', stderr: 'ignore' });
  return new TextDecoder().decode(result.stdout).trim() || 'unknown';
}

export function renderBuildInfoModule(version: string, commitHash: string): string {
  return `// Generated by scripts/build/compile-binary.ts. Do not edit.\nexport const buildInfo = ${JSON.stringify({ version, commitHash })} as const;\n`;
}

function targetFlag(target: ReleaseTarget): string {
  return `bun-${target}`;
}

function outputName(target: ReleaseTarget): string {
  return target === 'windows-x64' ? 'myadmin.exe' : 'myadmin';
}

const defaultRunner = async (command: string[]): Promise<number> => {
  const child = Bun.spawn(command, { stdout: 'inherit', stderr: 'inherit' });
  return child.exited;
};

export async function compileBinaries(options: CompileBinaryOptions = {}): Promise<string[]> {
  const root = resolve(options.repositoryRoot ?? process.cwd());
  const targets = options.targets ?? RELEASE_TARGETS;
  const assetsOutput = resolve(root, 'packages/runtime-assets/src/embedded-assets.generated.ts');
  const buildInfoOutput = resolve(root, 'apps/cli/src/runtime/build-info.generated.ts');
  const originalAssets = await readFile(assetsOutput, 'utf8');
  const originalBuildInfo = await readFile(buildInfoOutput, 'utf8');
  const version = options.version ?? releaseVersion();
  const commitHash = options.commitHash ?? releaseCommitHash();
  const run = options.commandRunner ?? defaultRunner;
  const outputs: string[] = [];

  try {
    await embedWebAssets({
      repositoryRoot: root,
      outputPath: 'packages/runtime-assets/src/embedded-assets.generated.ts',
    });
    await writeFile(buildInfoOutput, renderBuildInfoModule(version, commitHash), 'utf8');
    for (const target of targets) {
      const directory = resolve(root, 'dist/binaries', target);
      const output = join(directory, outputName(target));
      await mkdir(directory, { recursive: true });
      const command = [
        process.execPath,
        'build',
        '--compile',
        `--target=${targetFlag(target)}`,
        `--outfile=${output}`,
        'apps/cli/src/main.ts',
      ];
      if (target === 'windows-x64') command.push('--windows-hide-console');
      const exitCode = await run(command);
      if (exitCode !== 0)
        throw new Error(`Bun Compile failed for ${target} with exit code ${exitCode}`);
      outputs.push(output);
    }
  } finally {
    await writeFile(assetsOutput, originalAssets, 'utf8');
    await writeFile(buildInfoOutput, originalBuildInfo, 'utf8');
  }
  return outputs;
}

function cliTargets(args: readonly string[]): readonly ReleaseTarget[] | undefined {
  const values: string[] = [];
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument?.startsWith('--target=')) values.push(argument.slice('--target='.length));
    else if (argument === '--target' && args[index + 1]) values.push(args[++index] as string);
  }
  if (values.length === 0) return undefined;
  if (values.some((value) => !RELEASE_TARGETS.includes(value as ReleaseTarget))) {
    throw new Error(`Target must be one of: ${RELEASE_TARGETS.join(', ')}`);
  }
  return values as ReleaseTarget[];
}

if (import.meta.main) {
  const result = await compileBinaries({ targets: cliTargets(process.argv.slice(2)) });
  for (const output of result) console.log(`Compiled ${output}`);
}
